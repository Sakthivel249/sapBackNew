import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error
import torch
import torch.nn as nn
from torch.utils.data import DataLoader, TensorDataset

class LSTMModel(nn.Module):
    def __init__(self, input_size=1, hidden_size=50, num_layers=1):
        super(LSTMModel, self).__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers, batch_first=True)
        self.dropout = nn.Dropout(0.2)
        self.fc = nn.Linear(hidden_size, 1)

    def forward(self, x):
        out, _ = self.lstm(x)
        out = self.dropout(out[:, -1, :])
        return self.fc(out)

class PyTorchForecast:
    def __init__(self, file_path, look_back=30):
        self.file_path = file_path
        self.look_back = look_back
        self.scaler = MinMaxScaler()
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    def preprocess_data(self):
        df = pd.read_csv(self.file_path)
        df["Total Sales"] = (
            df["Idly"]
            + df["Pongal"] * 5
            + df["Sambar Rice"] * 5
            + df["Curd Rice"] * 3
            + df["Lemon Rice"] * 5
            + df["CurryLeaf Rice"] * 5
        )
        df = df[["Date", "Total Sales"]]
        df["Date"] = pd.to_datetime(df["Date"], format="%d-%m-%Y")
        df.sort_values("Date", inplace=True)
        df.set_index("Date", inplace=True)
        self.df = df

        scaled_data = self.scaler.fit_transform(df[["Total Sales"]])
        X, y = self.create_sequences(scaled_data)

        split = int(len(X) * 0.9)
        self.X_train, self.X_test = X[:split], X[split:]
        self.y_train, self.y_test = y[:split], y[split:]

        self.train_loader = DataLoader(
            TensorDataset(torch.from_numpy(self.X_train).float(),
                          torch.from_numpy(self.y_train).float()),
            batch_size=32, shuffle=True
        )
        self.X_test_torch = torch.from_numpy(self.X_test).float().to(self.device)

    def create_sequences(self, data):
        X, y = [], []
        for i in range(self.look_back, len(data)):
            X.append(data[i - self.look_back:i, 0])
            y.append(data[i, 0])
        return np.array(X).reshape(-1, self.look_back, 1), np.array(y).reshape(-1, 1)

    def build_model(self):
        self.model = LSTMModel().to(self.device)
        self.loss_fn = nn.MSELoss()
        self.optimizer = torch.optim.Adam(self.model.parameters(), lr=0.001)

    def train_model(self, epochs=20):
        self.model.train()
        for epoch in range(epochs):
            total_loss = 0
            for batch_X, batch_y in self.train_loader:
                batch_X, batch_y = batch_X.to(self.device), batch_y.to(self.device)
                self.optimizer.zero_grad()
                output = self.model(batch_X)
                loss = self.loss_fn(output, batch_y)
                loss.backward()
                self.optimizer.step()
                total_loss += loss.item()
            print(f"Epoch {epoch+1}/{epochs}, Loss: {total_loss / len(self.train_loader):.6f}")

    def evaluate_model(self):
        self.model.eval()
        with torch.no_grad():
            predictions = self.model(self.X_test_torch).cpu().numpy()
        y_pred_inverse = self.scaler.inverse_transform(predictions)
        y_test_inverse = self.scaler.inverse_transform(self.y_test)

        rmse = np.sqrt(mean_squared_error(y_test_inverse, y_pred_inverse))
        mae = mean_absolute_error(y_test_inverse, y_pred_inverse)
        mape = self.mean_absolute_percentage_error(y_test_inverse, y_pred_inverse)

        print(f"RMSE: {rmse}")
        print(f"MAE: {mae}")
        print(f"MAPE: {mape}")

        self.y_test_inverse = y_test_inverse
        self.y_pred_inverse = y_pred_inverse
        self.residual_std = np.std(y_test_inverse - y_pred_inverse)

    def mean_absolute_percentage_error(self, y_true, y_pred):
        return np.mean(np.abs((y_true - y_pred) / y_true)) * 100

    def plot_predictions(self):
        plt.figure(figsize=(12, 6))
        plt.plot(self.y_test_inverse, label='Actual Sales', color='blue')
        plt.plot(self.y_pred_inverse, label='Predicted Sales', color='orange')

        ci = 1.96 * self.residual_std
        upper = self.y_pred_inverse + ci
        lower = self.y_pred_inverse - ci

        plt.fill_between(range(len(self.y_pred_inverse)), lower.flatten(), upper.flatten(),
                         color='orange', alpha=0.2, label='95% Confidence Interval')

        plt.title("Forecast vs Actual")
        plt.xlabel("Time Step")
        plt.ylabel("Sales")
        plt.legend()
        plt.grid(True)
        plt.tight_layout()
        plt.show()

