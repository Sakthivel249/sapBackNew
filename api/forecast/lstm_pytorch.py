import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error
import torch
import torch.nn as nn
from torch.utils.data import DataLoader, TensorDataset

class LSTMModel(nn.Module):
    def __init__(self, input_size=1, hidden_size=50, num_layers=1):
        super(LSTMModel, self).__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers, batch_first=True)
        self.dropout = nn.Dropout(0.2)
        self.fc = nn.Linear(hidden_size, 1)

    def forward(self, x):
        out, _ = self.lstm(x)
        out = self.dropout(out[:, -1, :])
        return self.fc(out)

class PyTorchForecast:
    def __init__(self, file_path, look_back=30):
        self.file_path = file_path
        self.look_back = look_back
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.food_items = ["Idly", "Pongal", "Sambar Rice", "Curd Rice", "Lemon Rice", "CurryLeaf Rice"]
        self.models = {}
        self.scalers = {}
        self.data = {}

    def preprocess_data(self):
        df = pd.read_csv(self.file_path)
        df["Date"] = pd.to_datetime(df["Date"], format="%d-%m-%Y")
        df.sort_values("Date", inplace=True)
        df.set_index("Date", inplace=True)
        df = df[self.food_items]

        for item in self.food_items:
            scaler = MinMaxScaler()
            data_scaled = scaler.fit_transform(df[[item]])
            self.scalers[item] = scaler

            X, y = self.create_sequences(data_scaled)

            split = int(len(X) * 0.9)
            X_train, X_test = X[:split], X[split:]
            y_train, y_test = y[:split], y[split:]

            train_loader = DataLoader(
                TensorDataset(torch.from_numpy(X_train).float(),
                              torch.from_numpy(y_train).float()),
                batch_size=32, shuffle=True
            )

            self.data[item] = {
                "X_train": X_train,
                "X_test": X_test,
                "y_train": y_train,
                "y_test": y_test,
                "train_loader": train_loader,
                "X_test_torch": torch.from_numpy(X_test).float().to(self.device)
            }

    def create_sequences(self, data):
        X, y = [], []
        for i in range(self.look_back, len(data)):
            X.append(data[i - self.look_back:i, 0])
            y.append(data[i, 0])
        return np.array(X).reshape(-1, self.look_back, 1), np.array(y).reshape(-1, 1)

    def build_models(self):
        for item in self.food_items:
            model = LSTMModel().to(self.device)
            loss_fn = nn.MSELoss()
            optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
            self.models[item] = {"model": model, "loss_fn": loss_fn, "optimizer": optimizer}

    def train_models(self, epochs=20):
        for item in self.food_items:
            print(f"Training model for {item}")
            model_info = self.models[item]
            model = model_info["model"]
            loss_fn = model_info["loss_fn"]
            optimizer = model_info["optimizer"]
            train_loader = self.data[item]["train_loader"]

            model.train()
            for epoch in range(epochs):
                total_loss = 0
                for batch_X, batch_y in train_loader:
                    batch_X, batch_y = batch_X.to(self.device), batch_y.to(self.device)
                    optimizer.zero_grad()
                    output = model(batch_X)
                    loss = loss_fn(output, batch_y)
                    loss.backward()
                    optimizer.step()
                    total_loss += loss.item()
                print(f"{item} - Epoch {epoch+1}/{epochs}, Loss: {total_loss / len(train_loader):.6f}")

    def evaluate_models(self):
        for item in self.food_items:
            model = self.models[item]["model"]
            model.eval()
            X_test = self.data[item]["X_test"]
            y_test = self.data[item]["y_test"]
            X_test_torch = self.data[item]["X_test_torch"]
            scaler = self.scalers[item]

            with torch.no_grad():
                predictions = model(X_test_torch).cpu().numpy()

            y_pred_inverse = scaler.inverse_transform(predictions)
            y_test_inverse = scaler.inverse_transform(y_test)

            rmse = np.sqrt(mean_squared_error(y_test_inverse, y_pred_inverse))
            mae = mean_absolute_error(y_test_inverse, y_pred_inverse)
            mape = self.mean_absolute_percentage_error(y_test_inverse, y_pred_inverse)

            print(f"\n{item} Forecast:")
            print(f"RMSE: {rmse:.2f}, MAE: {mae:.2f}, MAPE: {mape:.2f}")

    def mean_absolute_percentage_error(self, y_true, y_pred):
        return np.mean(np.abs((y_true - y_pred) / y_true)) * 100

    def plot_predictions(self, item):
        model = self.models[item]["model"]
        model.eval()
        X_test_torch = self.data[item]["X_test_torch"]
        y_test = self.data[item]["y_test"]
        scaler = self.scalers[item]

        with torch.no_grad():
            predictions = model(X_test_torch).cpu().numpy()

        y_pred_inverse = scaler.inverse_transform(predictions)
        y_test_inverse = scaler.inverse_transform(y_test)
        residual_std = np.std(y_test_inverse - y_pred_inverse)

        plt.figure(figsize=(12, 6))
        plt.plot(y_test_inverse, label='Actual Sales', color='blue')
        plt.plot(y_pred_inverse, label='Predicted Sales', color='orange')

        ci = 1.96 * residual_std
        upper = y_pred_inverse + ci
        lower = y_pred_inverse - ci

        plt.fill_between(range(len(y_pred_inverse)), lower.flatten(), upper.flatten(),
                         color='orange', alpha=0.2, label='95% Confidence Interval')

        plt.title(f"{item} Forecast vs Actual")
        plt.xlabel("Time Step")
        plt.ylabel("Sales")
        plt.legend()
        plt.grid(True)
        plt.tight_layout()
        plt.show()

